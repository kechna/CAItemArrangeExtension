import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { collectWorldMeshes } from "./meshes/collectWorldMeshes.ts";
import { toMeshSize } from "./meshes/meshSize.ts";
import { findMediaSources } from "./meshes/sources.ts";

const OUTPUT = fileURLToPath(
  new URL("../common/media/lua/shared/CAItemArrangerExtension/IAMeshSizes_Generated.lua", import.meta.url),
);

const naturalCompare = (a: string, b: string): number => a.localeCompare(b, "en", { numeric: true });

const { GAME_FILES_PATH, LOCAL_MODS_PATH, STEAM_WORKSHOP_CONTENT_PATH } = process.env;

if (!GAME_FILES_PATH) {
  throw new Error("GAME_FILES_PATH is not set, see .env.template");
}

const sources = findMediaSources({
  gameFilesPath: GAME_FILES_PATH,
  workshopContentPath: STEAM_WORKSHOP_CONTENT_PATH,
  localModsPath: LOCAL_MODS_PATH,
});
const { models, skipped } = collectWorldMeshes(sources);

/** offsets smaller than this (in tiles or floors) aren't worth writing */
const MIN_OFFSET = 0.002;

const bySource = new Map<string, string[]>();
let lifted = 0;
let lowered = 0;
let shifted = 0;

for (const model of models) {
  const size = toMeshSize(model.extents, model.transform);
  const fields = [`dx = ${size.dx}`, `dy = ${size.dy}`, `dz = ${size.dz}`];

  for (const key of ["oz", "cx", "cy"] as const) {
    if (Math.abs(size[key]) >= MIN_OFFSET) {
      fields.push(`${key} = ${size[key]}`);
    }
  }

  if (Math.abs(size.oz) >= MIN_OFFSET) {
    if (size.oz > 0) {
      lifted++;
    } else {
      lowered++;
    }
  }

  if (Math.abs(size.cx) >= MIN_OFFSET || Math.abs(size.cy) >= MIN_OFFSET) {
    shifted++;
  }

  const line = `  [${JSON.stringify(model.key)}] = { ${fields.join(", ")} }, -- ${model.mesh}`;

  bySource.set(model.source, [...(bySource.get(model.source) ?? []), line]);
}

const lines = [
  "-- generated by src/generateMeshSizes.ts from the world item models of the game and the mods installed when it ran,",
  "-- do not edit. run `bun run generate:meshes`",
  "--",
  "-- model name in lowercase (+ `@weapon` when drawn through the weapon path, i.e. without a WorldStaticModel) -> the",
  "-- model on the ground at its script's scale, before Item Arrange turns it: dx/dy in tiles, dz in floors. oz is how",
  "-- far it reaches below its origin in floors (negative: it floats above it), cx/cy where its footprint's centre is",
  "-- relative to its origin in tiles. offsets are left out when negligible",
  "",
  "---@type table<string, { dx: number, dy: number, dz: number, oz?: number, cx?: number, cy?: number }>",
  "local MeshSizes = {",
];

const sourceIds = [...bySource.keys()].sort((a, b) =>
  a === "vanilla" ? -1 : b === "vanilla" ? 1 : naturalCompare(a, b),
);

for (const source of sourceIds) {
  lines.push(`  -- ${source}`, ...bySource.get(source)!.sort(naturalCompare));
}

lines.push("}", "", "return MeshSizes", "");

writeFileSync(OUTPUT, lines.join("\n"));

console.log(
  `Wrote ${models.length} models from ${bySource.size} of ${sources.length} sources (${skipped.length} missing or unreadable)`,
);
console.log(`Bottom offsets: ${lifted} models reach below their origin, ${lowered} float above it`);
console.log(`Footprint offsets: ${shifted} models aren't centred on their origin`);
