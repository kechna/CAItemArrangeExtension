import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { extractContainerSurfaces, type Surface } from "./extractSurfaces.ts";
import { parseTileDefinitions, parseTileGeometry } from "./tileGeometry.ts";

const OUTPUT = fileURLToPath(
  new URL("../common/media/lua/shared/CAItemArrangerExtension/IASurfaces_Generated.lua", import.meta.url),
);

const KEYS = ["zmin", "zmax", "xmin", "xmax", "ymin", "ymax"] as const satisfies (keyof Surface)[];

const formatNumber = (value: number): string => value.toFixed(3);

const formatSurface = (surface: Surface, index: number): string => {
  const fields = KEYS.map((key) => `${key} = ${formatNumber(surface[key])}`).join(", ");

  return `    [${index + 1}] = { ${fields} },`;
};

const naturalCompare = (a: string, b: string): number => a.localeCompare(b, "en", { numeric: true });

const gameFilesPath = process.env.GAME_FILES_PATH;

if (!gameFilesPath) {
  throw new Error("GAME_FILES_PATH is not set, see .env.template");
}

const media = path.join(gameFilesPath, "media");
const geometry = parseTileGeometry(readFileSync(path.join(media, "tileGeometry.txt"), "utf8"));
const definitions = parseTileDefinitions(readFileSync(path.join(media, "newtiledefinitions.tiles.txt"), "utf8"));
const { surfaces, ambiguous } = extractContainerSurfaces(geometry, definitions);

const lines = [
  "-- generated by src/generateSurfaces.ts from tileGeometry.txt, do not edit. run `bun run generate:surfaces`",
  "-- skipped corner shelves, these need a hand-picked arm in IAData.lua:",
  ...ambiguous.sort(naturalCompare).map((sprite) => `--   ${sprite}`),
  "",
  "---@type table<string, table[]>",
  "local Surfaces = {",
];

for (const sprite of [...surfaces.keys()].sort(naturalCompare)) {
  lines.push(`  ["${sprite}"] = {`, ...surfaces.get(sprite)!.map(formatSurface), "  },");
}

lines.push("}", "", "return Surfaces", "");

writeFileSync(OUTPUT, lines.join("\n"));

console.log(`Wrote ${surfaces.size} tiles to ${path.relative(process.cwd(), OUTPUT)} (${ambiguous.length} skipped)`);
